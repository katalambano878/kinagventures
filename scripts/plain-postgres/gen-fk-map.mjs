#!/usr/bin/env node
// Generates lib/db/fk-map.ts from a pg_dump --schema-only file.
//
//   node scripts/plain-postgres/gen-fk-map.mjs <schema.sql> [out.ts] [--tables=a,b,c]
//
// - FK_MAP:        every public -> public foreign key (FKs into auth.* are
//                  left out: the data API never embeds auth tables).
// - JSONB_COLUMNS: every json/jsonb column per public table. The compat
//                  layer sends these as JSON text; any other array value is
//                  passed to pg as a Postgres array.
// - ARRAY_COLUMNS: every Postgres array column (text[], uuid[], ...), for
//                  reference; values for these pass through as JS arrays.
// - PUBLIC_TABLES: the public tables the data API (/rest/v1) may touch.
//                  With --tables=a,b,c only those (each must exist in the
//                  dump); without it every table and view in schema public.
//                  Kinag Ventures passes the tables its code queries
//                  (grep `.from('...')`) plus the tables it embeds.
//
// Regenerate whenever a migration changes the public schema.

import { readFileSync, writeFileSync } from "fs";
import path from "path";

const args = process.argv.slice(2);
const tablesFlag = args.find((a) => a.startsWith("--tables="));
const [dumpPath, outArg] = args.filter((a) => !a.startsWith("--"));
if (!dumpPath) {
  console.error("usage: gen-fk-map.mjs <schema.sql> [out.ts] [--tables=a,b,c]");
  process.exit(1);
}
const outPath = outArg || path.join(process.cwd(), "lib/db/fk-map.ts");
const sql = readFileSync(dumpPath, "utf8");

const unq = (s) => s.replace(/^"|"$/g, "");

// ---- tables, views and their columns ---------------------------------------
const tables = new Set();
const jsonb = new Map();
const arrays = new Map();

const tableRe = /^CREATE (?:UNLOGGED )?TABLE public\.("?[A-Za-z0-9_]+"?) \(\n([\s\S]*?)\n\);/gm;
for (const m of sql.matchAll(tableRe)) {
  const table = unq(m[1]);
  tables.add(table);
  for (const rawLine of m[2].split("\n")) {
    const line = rawLine.trim().replace(/,$/, "");
    if (!line || /^(CONSTRAINT|PRIMARY KEY|UNIQUE|CHECK|FOREIGN KEY|EXCLUDE)\b/i.test(line)) continue;
    const col = /^("[^"]+"|[A-Za-z_][A-Za-z0-9_]*)\s+(.+)$/.exec(line);
    if (!col) continue;
    const name = unq(col[1]);
    // The type is everything before DEFAULT / NOT NULL / GENERATED / ...
    const type = col[2].split(/\s+(?:DEFAULT|NOT NULL|NULL|GENERATED|COLLATE|CONSTRAINT)\b/i)[0].trim();
    if (/^jsonb?$/i.test(type)) {
      if (!jsonb.has(table)) jsonb.set(table, new Set());
      jsonb.get(table).add(name);
    } else if (/\[\]$/.test(type)) {
      if (!arrays.has(table)) arrays.set(table, new Set());
      arrays.get(table).add(name);
    }
  }
}

const viewRe = /^CREATE (?:MATERIALIZED )?VIEW public\.("?[A-Za-z0-9_]+"?)/gm;
for (const m of sql.matchAll(viewRe)) tables.add(unq(m[1]));

// ---- foreign keys -------------------------------------------------------------
const fks = new Map();
const fkRe =
  /ALTER TABLE ONLY public\.("?[A-Za-z0-9_]+"?)\s+ADD CONSTRAINT ("?[A-Za-z0-9_]+"?) FOREIGN KEY \(([^)]+)\) REFERENCES ([a-z_]+)\.("?[A-Za-z0-9_]+"?)\(([^)]+)\)/g;
for (const m of sql.matchAll(fkRe)) {
  const [, tableRaw, , colsRaw, schema, foreignRaw, foreignColsRaw] = m;
  if (schema !== "public") continue;
  const cols = colsRaw.split(",").map((c) => unq(c.trim()));
  const fcols = foreignColsRaw.split(",").map((c) => unq(c.trim()));
  if (cols.length !== 1) continue; // composite keys cannot be embedded by the compat layer
  const table = unq(tableRaw);
  if (!fks.has(table)) fks.set(table, []);
  fks.get(table).push({ column: cols[0], foreignTable: unq(foreignRaw), foreignColumn: fcols[0] });
}

// ---- tables the data API may touch -------------------------------------------
let apiTables = tables;
if (tablesFlag) {
  const wanted = tablesFlag.slice("--tables=".length).split(",").map((t) => t.trim()).filter(Boolean);
  const missing = wanted.filter((t) => !tables.has(t));
  if (missing.length) {
    console.error(`not in the schema dump: ${missing.join(", ")}`);
    process.exit(1);
  }
  apiTables = new Set(wanted);
}

// ---- output -------------------------------------------------------------------
const sorted = (it) => [...it].sort();
const setLine = (cols) => `new Set([${sorted(cols).map((c) => JSON.stringify(c)).join(", ")}])`;

let out = `// Foreign-key map for PostgREST-style embeds — Kinag Ventures.
// GENERATED by scripts/plain-postgres/gen-fk-map.mjs from the schema dump; do not edit by hand.
// Regenerate if the public schema changes.
export interface FkEdge {
  column: string;
  foreignTable: string;
  foreignColumn: string;
}

/** json/jsonb columns per table: values are sent to Postgres as JSON text. */
export const JSONB_COLUMNS: Record<string, Set<string>> = {
${sorted(jsonb.keys()).map((t) => `  ${t}: ${setLine(jsonb.get(t))},`).join("\n")}
};

/** Postgres array columns per table (text[], uuid[], ...): JS arrays pass through as-is. */
export const ARRAY_COLUMNS: Record<string, Set<string>> = {
${sorted(arrays.keys()).map((t) => `  ${t}: ${setLine(arrays.get(t))},`).join("\n")}
};

/** Every public -> public foreign key (FKs into auth.* omitted). */
export const FK_MAP: Record<string, FkEdge[]> = {
${sorted(fks.keys())
  .map((t) => {
    const edges = fks
      .get(t)
      .sort((a, b) => a.column.localeCompare(b.column))
      .map((e) => `    { column: ${JSON.stringify(e.column)}, foreignTable: ${JSON.stringify(e.foreignTable)}, foreignColumn: ${JSON.stringify(e.foreignColumn)} },`)
      .join("\n");
    return `  ${t}: [\n${edges}\n  ],`;
  })
  .join("\n")}
};

/**
 * The public tables the data API (/rest/v1) may touch, top-level or embedded
 * (${apiTables.size} of the ${tables.size} in the schema): ${tablesFlag ? "the tables this app's code queries and embeds" : "every table and view in schema public"}.
 * Anything else (other public tables, pg_roles, pg_settings, auth.*,
 * storage.*) is refused before any SQL runs.
 */
export const PUBLIC_TABLES: ReadonlySet<string> = new Set([
${sorted(apiTables).map((t) => `  ${JSON.stringify(t)},`).join("\n")}
]);
`;

writeFileSync(outPath, out);
console.log(
  `wrote ${outPath}: ${apiTables.size}/${tables.size} tables for the API, ${[...fks.values()].flat().length} foreign keys, ` +
    `${[...jsonb.values()].reduce((n, s) => n + s.size, 0)} json columns, ` +
    `${[...arrays.values()].reduce((n, s) => n + s.size, 0)} array columns`
);
